require('dotenv').config();
import express, { json } from 'express'; import cors from 'cors'; import cookieParser from 'cookie-parser';
import connectDB from './config/db'; import authRoutes from './routes/authRoutes'; import dataRoutes from './routes/dataRoutes';
const app=express();
app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173',credentials:true}));
app.use(json({limit:'1mb'})); app.use(cookieParser());
app.get('/api/health',(req,res)=>res.json({status:'ok',app:'FitTrack API'}));
app.use('/api/auth',authRoutes); app.use('/api',dataRoutes);
app.use((req,res)=>res.status(404).json({message:'Route not found'}));
app.use((err,req,res,next)=>{console.error(err);if(err.name==='ValidationError')return res.status(400).json({message:err.message});if(err.code===11000)return res.status(409).json({message:'A record with this value already exists.'});res.status(500).json({message:process.env.NODE_ENV==='production'?'Something went wrong.':err.message});});
const start=async()=>{try{await connectDB();const port=process.env.PORT||5000;app.listen(port,()=>console.log(`FitTrack API listening on ${port}`));}catch(err){console.error('Startup failed:',err.message);process.exit(1)}};
start();
